#!/usr/bin/env python3
"""串关期望值计算 v2：修复漏洞#6（资金分配拍脑袋）。

核心修正：不拿自己拍脑袋的命中率自嗨，而是**对比市场隐含概率**。
北单 SP 是派奖倍数，返奖率约 65-75%。公平概率 ≈ 返奖率 / SP。

判断标准（诚实）：
- 我的估计概率 p > 市场隐含概率 → 说明我认为自己比市场强（要有情报依据）
- 我的估计概率 p < 市场隐含概率 → 这注不该碰
- 期望值 = p^串数 × SP乘积 - 1，只有 p 真有 edge 时才可能为正
"""
import itertools

PAYOUT_RATE = 0.70  # 北单返奖率估计（65-75%，取中）


def implied_prob(sp):
    """市场隐含概率 = 返奖率 / SP"""
    return PAYOUT_RATE / sp


def main():
    # 昨天的方案
    # (标签, SP, 我的估计概率p)
    ticket1 = [
        ('北西兰2:0', 4.80, 0.20),   # 领先+主场+对手弱，估20%
        ('奥莫尼亚1:0', 4.76, 0.20),
        ('哈马比1:0', 4.74, 0.20),
        ('中日德兰1:0', 4.60, 0.20),
        ('扎布热1:1', 4.59, 0.22),
        ('明斯克1:1', 4.93, 0.22),
    ]
    ticket2 = [
        ('贝西克塔斯2:0', 21.91, 0.06),
        ('瓦杜兹1:2', 44.96, 0.04),
        ('流浪者2:1', 34.77, 0.04),
        ('哈茨1:3', 152.07, 0.02),
        ('伊尔维斯1:1', 4.65, 0.20),
    ]

    print('=' * 72)
    print('串关期望值 v2：对比市场隐含概率（返奖率假设70%）')
    print('=' * 72)

    for name, ticket in [('票1 保底6场', ticket1), ('票2 梦幻5场', ticket2)]:
        print(f'\n### {name}')
        print(f'{"选项":<16} {"SP":>7} {"市场隐含":>8} {"我的估计":>8} {"edge":>7}')
        print('-' * 52)
        for label, sp, p in ticket:
            imp = implied_prob(sp)
            edge = p - imp
            mark = '⚠️自欺' if edge > 0 and p > 0.10 else ('✅' if edge > 0 else '❌')
            print(f'{label:<16} {sp:>7.2f} {imp*100:>7.1f}% {p*100:>7.1f}% {edge*100:>+6.1f}% {mark}')

    print('\n' + '=' * 72)
    print('核心结论（诚实版）:')
    print('1. 市场隐含概率 = 返奖率/SP。梦幻场 SP 越高，市场认为它概率越低')
    print('2. 比如瓦杜兹1:2 SP=44.96 → 市场隐含仅 1.6%，我给 4% = 赌自己比市场强2.5倍')
    print('3. 我们目前 18/114=15.8% 只略超基线，尚未证明有稳定 edge')
    print('4. 串关期望值 = p^串数×SP乘积 - 1，长期必为负，除非真有情报 edge')
    print('5. 结论不变：串关当娱乐，小钱博大；别把"我感觉能中"当 edge')
    print('=' * 72)


if __name__ == '__main__':
    main()
